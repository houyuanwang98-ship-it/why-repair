"""Shared validation and agreement utilities for the M2 pilot benchmark.

The module intentionally validates annotation structure, not mathematical
truth.  Gold labels are created only from agreement or explicit adjudication.
"""

from __future__ import annotations

import json
import hashlib
import math
from collections import Counter
from pathlib import Path
from typing import Any, Iterable


SCHEMA_VERSION = "m2.1"
VALIDITY_STATUSES = {"valid", "valid_with_gap", "invalid", "undetermined"}
ERROR_TYPES = {
    "quantifier_error",
    "missing_assumption",
    "theorem_misuse",
    "algebraic_invalidity",
    "proof_gap",
    "target_shift",
    "false_generalization",
    "no_error",
    "undetermined",
}
COUNTEREXAMPLE_STATUSES = {"not_applicable", "valid", "invalid", "undetermined"}
AGREEMENT_FIELDS = (
    "validity_status",
    "first_gap_step",
    "first_invalid_step",
    "error_type",
    "counterexample_status",
    "minimal_repair",
)
KAPPA_FIELDS = frozenset(AGREEMENT_FIELDS) - {"minimal_repair"}


class M2ValidationError(ValueError):
    """Raised when M2 data violates the frozen structural contract."""


def sha256_file(path: str | Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_gold_manifest(
    source_path: str | Path,
    person_a_path: str | Path,
    person_b_path: str | Path,
    adjudications_path: str | Path,
    output_path: str | Path,
    row_count: int,
) -> dict[str, Any]:
    """Bind a gold artifact to every exact input and its generated bytes."""
    return {
        "artifact_type": "m2_adjudicated_gold",
        "contract_version": SCHEMA_VERSION,
        "generator": "scripts/build_m2_gold.py",
        "row_count": row_count,
        "inputs": {
            "source_sha256": sha256_file(source_path),
            "person_a_sha256": sha256_file(person_a_path),
            "person_b_sha256": sha256_file(person_b_path),
            "adjudications_sha256": sha256_file(adjudications_path),
        },
        "output_sha256": sha256_file(output_path),
    }


def source_id(row: dict[str, Any]) -> str:
    """Return the stable identifier from the M2 or legacy checker source shape."""
    value = row.get("proof_id", row.get("id"))
    return value if isinstance(value, str) else ""


def source_steps(row: dict[str, Any]) -> list[Any]:
    """Return ordered proof steps without discarding M2 node identifiers."""
    value = row.get("proof_steps", row.get("flawed_proof_steps"))
    return value if isinstance(value, list) else []


def read_jsonl(path: str | Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    source = Path(path)
    with source.open("r", encoding="utf-8") as handle:
        for line_number, raw in enumerate(handle, 1):
            if not raw.strip():
                continue
            try:
                row = json.loads(raw)
            except json.JSONDecodeError as exc:
                raise M2ValidationError(f"{source}:{line_number}: invalid JSON: {exc.msg}") from exc
            if not isinstance(row, dict):
                raise M2ValidationError(f"{source}:{line_number}: row must be a JSON object")
            rows.append(row)
    return rows


def write_jsonl(path: str | Path, rows: Iterable[dict[str, Any]]) -> None:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")


def _require(row: dict[str, Any], fields: Iterable[str], context: str) -> None:
    missing = [field for field in fields if field not in row]
    if missing:
        raise M2ValidationError(f"{context}: missing fields: {', '.join(missing)}")


def _unique(rows: list[dict[str, Any]], key: str, context: str) -> None:
    values = [row.get(key) for row in rows]
    duplicates = sorted(value for value, count in Counter(values).items() if count > 1)
    if duplicates:
        raise M2ValidationError(f"{context}: duplicate {key}: {duplicates}")


def validate_sources(rows: list[dict[str, Any]], expected_count: int | None = None) -> None:
    if expected_count is not None and len(rows) != expected_count:
        raise M2ValidationError(f"sources: expected {expected_count} rows, found {len(rows)}")
    for index, row in enumerate(rows, 1):
        context = f"source row {index}"
        is_m2_source = "proof_id" in row or "proof_steps" in row
        if is_m2_source:
            _require(row, ("schema_version", "proof_id", "theorem_version", "domain", "theorem", "assumptions", "proof_steps"), context)
            if row["schema_version"] != "m2-source-0.1":
                raise M2ValidationError(f"{context}: unsupported source schema_version {row['schema_version']!r}")
            if not isinstance(row["theorem_version"], int) or isinstance(row["theorem_version"], bool) or row["theorem_version"] < 1:
                raise M2ValidationError(f"{context}: theorem_version must be a positive integer")
        else:
            _require(row, ("id", "domain", "topic", "theorem", "assumptions", "flawed_proof_steps"), context)
        identifier = source_id(row)
        if not identifier.strip():
            raise M2ValidationError(f"{context}: proof_id/id must be a non-empty string")
        if not isinstance(row["theorem"], str) or not row["theorem"].strip():
            raise M2ValidationError(f"{context}: theorem must be a non-empty string")
        if not isinstance(row["assumptions"], list) or not all(isinstance(x, str) for x in row["assumptions"]):
            raise M2ValidationError(f"{context}: assumptions must be a string array")
        steps = source_steps(row)
        if is_m2_source:
            if not steps or not all(isinstance(x, dict) and isinstance(x.get("node_id"), str) and x["node_id"].strip() and isinstance(x.get("text"), str) and x["text"].strip() for x in steps):
                raise M2ValidationError(f"{context}: proof_steps must contain non-empty node_id/text objects")
            node_ids = [step["node_id"] for step in steps]
            if len(node_ids) != len(set(node_ids)):
                raise M2ValidationError(f"{context}: proof_steps contain duplicate node_id values")
        elif not steps or not all(isinstance(x, str) and x.strip() for x in steps):
            raise M2ValidationError(f"{context}: flawed_proof_steps must be a non-empty string array")
    identifiers = [source_id(row) for row in rows]
    duplicates = sorted(value for value, count in Counter(identifiers).items() if count > 1)
    if duplicates:
        raise M2ValidationError(f"sources: duplicate proof_id/id: {duplicates}")


def _validate_step(value: Any, step_count: int, field: str, context: str) -> None:
    if value is not None and (not isinstance(value, int) or isinstance(value, bool) or value < 1 or value > step_count):
        raise M2ValidationError(f"{context}: {field} must be null or an integer in [1, {step_count}]")


def validate_annotations(
    rows: list[dict[str, Any]],
    sources: list[dict[str, Any]],
    expected_annotator: str | None = None,
) -> None:
    validate_sources(sources)
    source_map = {source_id(row): row for row in sources}
    _unique(rows, "sample_id", "annotations")
    annotation_ids = {row.get("sample_id") for row in rows}
    if annotation_ids != set(source_map):
        missing = sorted(set(source_map) - annotation_ids)
        extra = sorted(annotation_ids - set(source_map), key=str)
        raise M2ValidationError(f"annotations: sample set mismatch; missing={missing}, extra={extra}")

    required = (
        "schema_version",
        "sample_id",
        "annotator_id",
        "validity_status",
        "first_gap_step",
        "first_invalid_step",
        "error_type",
        "counterexample_status",
        "minimal_repair",
        "notes",
    )
    for index, row in enumerate(rows, 1):
        context = f"annotation row {index}"
        _require(row, required, context)
        if row["schema_version"] != SCHEMA_VERSION:
            raise M2ValidationError(f"{context}: schema_version must be {SCHEMA_VERSION!r}")
        if not isinstance(row["annotator_id"], str) or not row["annotator_id"].strip():
            raise M2ValidationError(f"{context}: annotator_id must be a non-empty string")
        if expected_annotator is not None and row["annotator_id"] != expected_annotator:
            raise M2ValidationError(f"{context}: expected annotator_id {expected_annotator!r}")
        if row["validity_status"] not in VALIDITY_STATUSES:
            raise M2ValidationError(f"{context}: invalid validity_status {row['validity_status']!r}")
        if row["error_type"] not in ERROR_TYPES:
            raise M2ValidationError(f"{context}: invalid error_type {row['error_type']!r}")
        if row["counterexample_status"] not in COUNTEREXAMPLE_STATUSES:
            raise M2ValidationError(f"{context}: invalid counterexample_status {row['counterexample_status']!r}")
        step_count = len(source_steps(source_map[row["sample_id"]]))
        _validate_step(row["first_gap_step"], step_count, "first_gap_step", context)
        _validate_step(row["first_invalid_step"], step_count, "first_invalid_step", context)
        if row["validity_status"] == "valid" and (row["first_gap_step"] is not None or row["first_invalid_step"] is not None):
            raise M2ValidationError(f"{context}: valid annotations cannot name a gap or invalid step")
        if row["validity_status"] == "valid_with_gap" and row["first_gap_step"] is None:
            raise M2ValidationError(f"{context}: valid_with_gap requires first_gap_step")
        if row["validity_status"] == "invalid" and row["first_invalid_step"] is None:
            raise M2ValidationError(f"{context}: invalid requires first_invalid_step")
        if row["error_type"] == "no_error" and row["validity_status"] not in {"valid", "valid_with_gap"}:
            raise M2ValidationError(f"{context}: no_error conflicts with {row['validity_status']!r}")
        if row["minimal_repair"] is not None and not isinstance(row["minimal_repair"], str):
            raise M2ValidationError(f"{context}: minimal_repair must be null or a string")
        if not isinstance(row["notes"], str):
            raise M2ValidationError(f"{context}: notes must be a string")


def cohen_kappa(left: list[Any], right: list[Any]) -> float | None:
    if len(left) != len(right):
        raise ValueError("kappa inputs must have equal length")
    if not left:
        return None
    observed = sum(a == b for a, b in zip(left, right)) / len(left)
    left_counts = Counter(left)
    right_counts = Counter(right)
    expected = sum(left_counts[label] * right_counts[label] for label in set(left_counts) | set(right_counts)) / len(left) ** 2
    if math.isclose(expected, 1.0):
        return 1.0 if math.isclose(observed, 1.0) else None
    return (observed - expected) / (1.0 - expected)


def confusion_matrix(left: list[Any], right: list[Any]) -> list[dict[str, Any]]:
    """Return a JSON-safe sparse confusion matrix with A as rows and B as columns."""
    if len(left) != len(right):
        raise ValueError("confusion-matrix inputs must have equal length")
    counts = Counter(zip(left, right))
    return [
        {"person_a_value": a, "person_b_value": b, "count": count}
        for (a, b), count in sorted(counts.items(), key=lambda item: (str(item[0][0]), str(item[0][1])))
    ]


def build_agreement_report(
    left: list[dict[str, Any]],
    right: list[dict[str, Any]],
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    left_map = {row["sample_id"]: row for row in left}
    right_map = {row["sample_id"]: row for row in right}
    if set(left_map) != set(right_map):
        raise M2ValidationError("agreement: annotation sample sets differ")
    left_annotators = {row["annotator_id"] for row in left}
    right_annotators = {row["annotator_id"] for row in right}
    if len(left_annotators) != 1 or len(right_annotators) != 1:
        raise M2ValidationError("agreement: each annotation file must contain exactly one annotator_id")
    if left_annotators == right_annotators:
        raise M2ValidationError("agreement: Person A and Person B annotator_id values must differ")
    sample_ids = sorted(left_map)
    fields: dict[str, Any] = {}
    disagreements: list[dict[str, Any]] = []
    for field in AGREEMENT_FIELDS:
        left_values = [left_map[sample_id][field] for sample_id in sample_ids]
        right_values = [right_map[sample_id][field] for sample_id in sample_ids]
        matches = sum(a == b for a, b in zip(left_values, right_values))
        field_metrics = {
            "matches": matches,
            "total": len(sample_ids),
            "exact_agreement": matches / len(sample_ids) if sample_ids else None,
            "confusion_matrix": confusion_matrix(left_values, right_values),
            "cohen_kappa_applicable": field in KAPPA_FIELDS,
        }
        field_metrics["cohen_kappa"] = cohen_kappa(left_values, right_values) if field in KAPPA_FIELDS else None
        fields[field] = field_metrics
        for sample_id, a, b in zip(sample_ids, left_values, right_values):
            if a != b:
                disagreements.append(
                    {
                        "schema_version": SCHEMA_VERSION,
                        "sample_id": sample_id,
                        "field": field,
                        "person_a_value": a,
                        "person_b_value": b,
                    }
                )
    report = {
        "schema_version": SCHEMA_VERSION,
        "sample_count": len(sample_ids),
        "person_a_annotator": next(iter(left_annotators)),
        "person_b_annotator": next(iter(right_annotators)),
        "fields": fields,
        "disagreement_count": len(disagreements),
    }
    return report, disagreements


def create_adjudication_template(disagreements: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Create an intentionally incomplete, field-level adjudication queue."""
    return [
        {
            **row,
            "final_value": None,
            "disagreement_type": "",
            "evidence": [],
            "rationale": "",
            "adjudicators": [],
        }
        for row in disagreements
    ]


def _validate_adjudicated_field(field: str, value: Any, context: str) -> None:
    if field == "validity_status" and value not in VALIDITY_STATUSES:
        raise M2ValidationError(f"{context}: invalid final validity_status {value!r}")
    if field == "error_type" and value not in ERROR_TYPES:
        raise M2ValidationError(f"{context}: invalid final error_type {value!r}")
    if field == "counterexample_status" and value not in COUNTEREXAMPLE_STATUSES:
        raise M2ValidationError(f"{context}: invalid final counterexample_status {value!r}")
    if field in {"first_gap_step", "first_invalid_step"}:
        if value is not None and (not isinstance(value, int) or isinstance(value, bool) or value < 1):
            raise M2ValidationError(f"{context}: final {field} must be null or a positive integer")
    if field == "minimal_repair" and value is not None and not isinstance(value, str):
        raise M2ValidationError(f"{context}: final minimal_repair must be null or a string")
    if field not in AGREEMENT_FIELDS:
        raise M2ValidationError(f"{context}: unsupported adjudication field {field!r}")


def validate_adjudications(rows: list[dict[str, Any]], disagreements: list[dict[str, Any]]) -> None:
    required = (
        "schema_version",
        "sample_id",
        "field",
        "person_a_value",
        "person_b_value",
        "final_value",
        "disagreement_type",
        "evidence",
        "rationale",
        "adjudicators",
    )
    expected_rows: dict[tuple[str, str], dict[str, Any]] = {}
    for index, row in enumerate(disagreements, 1):
        context = f"disagreement row {index}"
        _require(row, ("schema_version", "sample_id", "field", "person_a_value", "person_b_value"), context)
        if row["schema_version"] != SCHEMA_VERSION:
            raise M2ValidationError(f"{context}: schema_version must be {SCHEMA_VERSION!r}")
        if row["field"] not in AGREEMENT_FIELDS:
            raise M2ValidationError(f"{context}: unsupported disagreement field {row['field']!r}")
        key = (row["sample_id"], row["field"])
        if key in expected_rows:
            raise M2ValidationError(f"{context}: duplicate disagreement {key}")
        expected_rows[key] = row
    expected = set(expected_rows)
    actual: set[tuple[str, str]] = set()
    for index, row in enumerate(rows, 1):
        context = f"adjudication row {index}"
        _require(row, required, context)
        if row["schema_version"] != SCHEMA_VERSION:
            raise M2ValidationError(f"{context}: schema_version must be {SCHEMA_VERSION!r}")
        key = (row["sample_id"], row["field"])
        if key in actual:
            raise M2ValidationError(f"{context}: duplicate adjudication {key}")
        actual.add(key)
        if key not in expected_rows:
            raise M2ValidationError(f"{context}: decision does not match a current disagreement {key}")
        current = expected_rows[key]
        if row["person_a_value"] != current["person_a_value"] or row["person_b_value"] != current["person_b_value"]:
            raise M2ValidationError(f"{context}: compared values do not match the current disagreement")
        _validate_adjudicated_field(row["field"], row["final_value"], context)
        if not isinstance(row["disagreement_type"], str) or not row["disagreement_type"].strip():
            raise M2ValidationError(f"{context}: disagreement_type must be non-empty")
        if not isinstance(row["rationale"], str) or not row["rationale"].strip():
            raise M2ValidationError(f"{context}: rationale must be non-empty")
        if not isinstance(row["evidence"], list) or not row["evidence"] or not all(isinstance(item, str) and item.strip() for item in row["evidence"]):
            raise M2ValidationError(f"{context}: evidence must be a non-empty array")
        if not isinstance(row["adjudicators"], list) or not all(isinstance(item, str) and item.strip() for item in row["adjudicators"]) or len(set(row["adjudicators"])) < 2:
            raise M2ValidationError(f"{context}: adjudicators must name at least two distinct reviewers")
    if actual != expected:
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        raise M2ValidationError(f"adjudications: coverage mismatch; missing={missing}, extra={extra}")


def build_gold(
    sources: list[dict[str, Any]],
    left: list[dict[str, Any]],
    right: list[dict[str, Any]],
    adjudications: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    _, disagreements = build_agreement_report(left, right)
    validate_adjudications(adjudications, disagreements)
    left_map = {row["sample_id"]: row for row in left}
    right_map = {row["sample_id"]: row for row in right}
    decisions = {(row["sample_id"], row["field"]): row["final_value"] for row in adjudications}
    gold: list[dict[str, Any]] = []
    resolved_annotations: list[dict[str, Any]] = []
    for source in sources:
        sample_id = source_id(source)
        labels: dict[str, Any] = {}
        for field in AGREEMENT_FIELDS:
            a = left_map[sample_id][field]
            b = right_map[sample_id][field]
            labels[field] = a if a == b else decisions[(sample_id, field)]
        resolved_annotations.append(
            {
                "schema_version": SCHEMA_VERSION,
                "sample_id": sample_id,
                "annotator_id": "joint_adjudication",
                **labels,
                "notes": "Resolved from independent annotations and explicit adjudication.",
            }
        )
        gold.append({**source, "gold_schema_version": SCHEMA_VERSION, **{f"gold_{k}": v for k, v in labels.items()}})
    validate_annotations(resolved_annotations, sources, expected_annotator="joint_adjudication")
    return gold
